#!/usr/bin/env node
// Builds the three tools' pages (character.html, lore.html, gm.html) and the player display (display.html) from
// desktop/template.html and js/tools.js.
//   node tools/make-pages.js
// Run it after changing the template, the tools' tabs, or the script list.
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm");
const ROOT = path.resolve(__dirname, "..");
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, "js/tools.js"), "utf8"), ctx);
const TOOLS = ctx.window.DUNE_TOOLS;
const template = fs.readFileSync(path.join(ROOT, "desktop/template.html"), "utf8");
const part = (n) => fs.readFileSync(path.join(ROOT, "desktop/parts", n), "utf8").replace(/\n$/, "");
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;");

for (const [tool, cfg] of Object.entries(TOOLS)) {
  const sw = Object.entries(TOOLS).map(([t, c]) => `<button class="tool-btn${t === tool ? " on" : ""}" data-act="openTool" data-tool="${t}"${t === tool ? ' aria-current="page"' : ""}>${esc(c.short)}</button>`).join("");
  const tabs = cfg.tabs.length > 1
    ? `  <nav class="tabs" id="tabs">\n${cfg.tabs.map(([id, label]) => `    <button data-tab="${id}">${esc(label)}</button>`).join("\n")}\n  </nav>`
    : `  <nav class="tabs tabs-hidden" id="tabs"></nav>`;
  const fill = {
    TOOL: tool, TITLE: esc("Dune " + cfg.title), SUB: tool === "gm" ? "" : "Dune: Adventures in the Imperium",
    POOLS: tool === "gm" ? part("gm-pools.html") : "", ACTIONS: tool === "gm" ? part("gm-actions.html") : "",
    DIALOG: tool === "gm" ? part("gm-dialog.html") : "", SWITCH: sw, TABS: tabs,
  };
  const html = template.replace(/^<!-- TEMPLATE[^\n]*\n/, `<!-- GENERATED by tools/make-pages.js from desktop/template.html; do not edit -->\n`)
    .replace(/\{\{(\w+)\}\}/g, (m, k) => (k in fill ? fill[k] : m));
  fs.writeFileSync(path.join(ROOT, tool + ".html"), html);
  console.log("wrote", tool + ".html");
}

// the player display (js/cast.js): the same scripts, no header or tabs, always the dark Imperial theme
const display = template.replace(/^<!-- TEMPLATE[^\n]*\n/, `<!-- GENERATED by tools/make-pages.js from desktop/template.html; do not edit -->\n`)
  .replace(/  <script>try \{ var t = localStorage[^\n]*\n/, "")
  .replace(/  <header class="topbar">[\s\S]*?<\/header>\n/, "")
  .replace("<body>", '<body class="cast-body">')
  .replace(/\{\{(\w+)\}\}/g, (m, k) => ({ TOOL: "display", TITLE: "Player Display", TABS: "", DIALOG: "" }[k] ?? m));
if (/\{\{\w+\}\}|class="topbar"/.test(display)) throw new Error("display.html: the template changed shape; update make-pages.js");
fs.writeFileSync(path.join(ROOT, "display.html"), display);
console.log("wrote display.html");
