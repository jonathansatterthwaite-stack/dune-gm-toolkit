#!/usr/bin/env node
// Builds the toolkit's page (index.html) and the player display (display.html) from desktop/template.html.
//   node tools/make-pages.js
// Run it after changing the template or the script list (and bump the ?v= numbers there when a CSS or JS file changes).
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "..");
const template = fs.readFileSync(path.join(ROOT, "desktop/template.html"), "utf8");
const part = (n) => fs.readFileSync(path.join(ROOT, "desktop/parts", n), "utf8").replace(/\n$/, "");
const GENERATED = `<!-- GENERATED by tools/make-pages.js from desktop/template.html; do not edit -->\n`;
const write = (name, html) => {
  if (/\{\{\w+\}\}/.test(html)) throw new Error(name + ": a {{placeholder}} wasn't filled; update make-pages.js");
  fs.writeFileSync(path.join(ROOT, name), html);
  console.log("wrote", name);
};

// the toolkit: the header with the workspaces, pools and session actions; the areas fill <main> (js/areas.js)
const fill = { TOOL: "toolkit", TITLE: "Dune GM Toolkit", POOLS: part("gm-pools.html"), ACTIONS: part("gm-actions.html"), DIALOG: part("gm-dialog.html") };
write("index.html", template.replace(/^<!-- TEMPLATE[^\n]*\n/, GENERATED).replace(/\{\{(\w+)\}\}/g, (m, k) => (k in fill ? fill[k] : m)));

// the player display (js/cast.js): the same scripts, no header, always the dark Imperial theme
const display = template.replace(/^<!-- TEMPLATE[^\n]*\n/, GENERATED)
  .replace(/  <script>try \{ var t = localStorage[^\n]*\n/, "")
  .replace(/  <header class="topbar">[\s\S]*?<\/header>\n/, "")
  .replace('<body class="layout">', '<body class="cast-body">')
  .replace(/\{\{(\w+)\}\}/g, (m, k) => ({ TOOL: "display", TITLE: "Player Display", DIALOG: "" }[k] ?? m));
if (/class="topbar"|class="layout"/.test(display)) throw new Error("display.html: the template changed shape; update make-pages.js");
write("display.html", display);
