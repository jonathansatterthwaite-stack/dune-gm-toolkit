#!/usr/bin/env python3
"""Extract character art from your own rulebook PDFs for the guided character creator.

    python tools/extract-art.py

Needs pypdfium2 and Pillow (pip install pypdfium2 pillow) and the PDFs in [rulebooks]/.
Writes transparent WebP cut-outs to img/local/ and a manifest to js/db/art.local.js.
Both are gitignored: personal use only, and the public site never loads them.
"""
import json
import os
import sys

import pypdfium2 as pdfium
import pypdfium2.raw as raw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOOKS = os.path.join(ROOT, "[rulebooks]")
OUT_DIR = os.path.join(ROOT, "img", "local", "factions")
MANIFEST = os.path.join(ROOT, "js", "db", "art.local.js")

# faction template -> (pdf, PDF page number, which figure on the page, printed page for the caption)
FACTIONS = {
    "": ("DUNE_CoreRules.pdf", 134, "largest", "Core p.125 (Kara Molay)"),
    "Bene Gesserit": ("DUNE_CoreRules.pdf", 119, "largest", "Core p.110"),
    "Fremen": ("DUNE_CoreRules.pdf", 120, "left", "Core p.111"),
    "Mentat": ("DUNE_CoreRules.pdf", 120, "right", "Core p.111"),
    "Spacing Guild": ("DUNE_CoreRules.pdf", 121, "left", "Core p.112"),
    "Suk Doctor": ("DUNE_CoreRules.pdf", 121, "right", "Core p.112"),
    "Sardaukar": ("DUNE_CoreRules.pdf", 297, "largest", "Core p.288"),
    "Tleilaxu Face Dancer": ("DUNE_PowerAndPawns.pdf", 48, "largest", "Power and Pawns p.44"),
    "Ginaz Cadet": ("DUNE_PowerAndPawns.pdf", 54, "largest", "Power and Pawns p.50"),
    "Ginaz Swordmaster": ("DUNE_PowerAndPawns.pdf", 54, "largest", "Power and Pawns p.50"),
    "CHOAM Agent": ("DUNE_PowerAndPawns.pdf", 125, "largest", "Power and Pawns p.121"),
}


def figures(page):
    """Cut-out figures on a page: images with transparency that aren't full-page backgrounds."""
    out = []
    for obj in page.get_objects(filter=[raw.FPDF_PAGEOBJ_IMAGE], max_depth=6):
        w, h = obj.get_px_size()
        if (w >= 1200 and h >= 1600) or w * h < 200000:
            continue
        img = obj.get_bitmap(render=True).to_pil().convert("RGBA")
        if img.getextrema()[3][0] == 255:  # fully opaque: a scene, not a cut-out
            continue
        left, _, right, _ = obj.get_bounds()
        out.append({"img": img, "x": (left + right) / 2, "area": w * h})
    return out


def slug(s):
    return "".join(c if c.isalnum() else "-" for c in (s or "house-agent").lower()).strip("-")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    docs, manifest = {}, {}
    for name, (pdf_name, pdf_page, pick, caption) in FACTIONS.items():
        path = os.path.join(BOOKS, pdf_name)
        if not os.path.exists(path):
            print("missing", path)
            continue
        doc = docs.setdefault(pdf_name, pdfium.PdfDocument(path))
        figs = figures(doc[pdf_page - 1])
        if not figs:
            print(f"no figure found for {name or 'House Agent'} on PDF page {pdf_page}")
            continue
        fig = (min(figs, key=lambda f: f["x"]) if pick == "left" else
               max(figs, key=lambda f: f["x"]) if pick == "right" else
               max(figs, key=lambda f: f["area"]))
        img = fig["img"]
        img = img.crop(img.getbbox())  # trim empty transparent margins
        if img.height > 1000:
            img = img.resize((round(img.width * 1000 / img.height), 1000))
        file = f"{slug(name)}.webp"
        img.save(os.path.join(OUT_DIR, file), "WEBP", quality=82, method=6)
        manifest[name] = {"src": f"img/local/factions/{file}", "w": img.width, "h": img.height, "caption": caption}
        print(f"{(name or 'House Agent'):22} {img.width}x{img.height}  <- {pdf_name} PDF page {pdf_page}")
    with open(MANIFEST, "w", encoding="utf-8") as f:
        f.write("// GENERATED by tools/extract-art.py from your own PDFs - personal use only. Gitignored; do not publish.\n")
        f.write("window.DUNE_ART = " + json.dumps({"factions": manifest}) + ";\n")
    print(f"Wrote {len(manifest)} images and {os.path.relpath(MANIFEST, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
